import path from 'path'
import { ADEVTOOL_DIR, getHostBinPath } from '../config/paths'
import { EmergencyNumberPreferences, Visibility } from '../proto-ts/vendor/adevtool/assets/emergency_number_preferences'
import { spawnAsync2 } from '../util/process'
import { getPhenotypeBytesFlag } from './phenotype'

export const SAFETYHUB_CONFIG_PACKAGE = 'com.google.android.apps.safetyhub#com.google.android.apps.safetyhub'

export async function decodeEmergencyNumbers(response: Buffer): Promise<{ textproto: Buffer; javaSource: string }> {
  let payload = getPhenotypeBytesFlag(response, SAFETYHUB_CONFIG_PACKAGE, '45716898')
  let proto = path.join(ADEVTOOL_DIR, 'assets', 'emergency_number_preferences.proto')
  let table = EmergencyNumberPreferences.decode(payload)
  let javaSource = generateEmergencyNumberPreferences(table)
  let textproto = await spawnAsync2({
    command: await getHostBinPath('aprotoc'),
    args: [`--proto_path=${path.dirname(proto)}`, '--decode=safetyhub.EmergencyNumberPreferences', proto],
    stdinData: payload,
  })
  return { textproto, javaSource }
}

export function generateEmergencyNumberPreferences(table: EmergencyNumberPreferences): string {
  if (!table.entries.length) {
    throw new Error('SafetyHub returned an empty emergency number preference table')
  }
  let countries = new Map<string, { numbers: Set<string>; primary: Set<string> }>()
  for (let entry of table.entries) {
    let { countryIso, number, visibility } = entry
    if (!countryIso || !number || !/^[A-Z]{2}$/.test(countryIso) || !/^[0-9]+$/.test(number)) {
      throw new Error('SafetyHub returned an invalid country or emergency number')
    }
    if (visibility !== Visibility.VISIBILITY_UNSPECIFIED && visibility !== Visibility.VISIBILITY_PREFERRED) {
      throw new Error(`Unsupported emergency number visibility ${visibility} for ${countryIso}/${number}`)
    }
    let country = countries.get(countryIso)
    if (!country) {
      country = { numbers: new Set(), primary: new Set() }
      countries.set(countryIso, country)
    }
    country.numbers.add(number)
    if (visibility === Visibility.VISIBILITY_PREFERRED) {
      country.primary.add(number)
    } else {
      country.primary.delete(number)
    }
  }

  let preferences = ''
  let primaries = ''
  for (let countryIso of [...countries.keys()].sort()) {
    let country = countries.get(countryIso)!
    let numbers = [...country.numbers].map(number => `"${number}"`).join(', ')
    preferences += `            case "${countryIso}":\n                yield Set.of(${numbers});\n`
    if (country.primary.size) {
      let primary = [...country.primary].map(number => `"${number}"`).join(', ')
      primaries += `            case "${countryIso}":\n                yield Set.of(${primary});\n`
    }
  }
  return `package com.android.settingslib.emergencynumber;

import java.util.Set;

// Generated by adevtool fetch-emergency-numbers. Do not edit.
// Source: Phenotype flag 45716898 in
// ${SAFETYHUB_CONFIG_PACKAGE}.
// Both methods describe one table: membership and primary status (visibility = 1).
// Sets express membership, not priority among their elements.
final class EmergencyNumberPreferences {
    private EmergencyNumberPreferences() {}

    static Set<String> getCountryPreferences(String country) {
        return switch (country) {
${preferences}            default:
                yield Set.of();
        };
    }

    // Restrict candidates to primary numbers only when at least one is available.
    static Set<String> getPrimaryNumbers(String country) {
        return switch (country) {
${primaries}            default:
                yield Set.of();
        };
    }
}
`
}
